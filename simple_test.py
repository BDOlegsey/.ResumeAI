"""
Простой тест для проверки наличия обновленных инструкций
"""
import json

def test_instructions_content():
    """Тест, проверяющий, что инструкции содержат информацию о обработке отсутствующих данных"""
    
    # Просто читаем файл с инструкциями
    with open('/workspace/core/agents/system_prompts.py', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Проверяем, что инструкции генератора содержат информацию о "..."
    assert "..." in content, "Инструкции должны содержать информацию о использовании '...'"
    assert "отсутствуют в профиле пользователя, используй значение" in content, "Инструкции должны содержать указание использовать '...' для отсутствующих данных"
    assert "генератор будет использовать" in content, "Инструкции других агентов должны учитывать использование '...' генератором"
    
    print("✓ Инструкции содержат информацию о обработке отсутствующих данных")

def test_schema_exists():
    """Тест, проверяющий, что схема существует"""
    
    # Проверяем, что файл схемы существует
    with open('/workspace/schema.json', 'r', encoding='utf-8') as f:
        schema = json.load(f)
    
    # Проверяем, что схема содержит хотя бы один формат
    assert len(schema) > 0, "Схема должна содержать хотя бы один формат резюме"
    
    # Проверяем, что все схемы валидны
    for template_name, schema_def in schema.items():
        # Проверяем, что это валидный JSON
        assert isinstance(schema_def, dict), f"Схема для {template_name} должна быть словарем"
        # Проверяем, что у схемы есть обязательные поля
        assert "type" in schema_def, f"Схема для {template_name} должна содержать тип"
        assert schema_def["type"] == "object", f"Схема для {template_name} должна быть объектом"
    
    print("✓ Схемы корректно определены")

def test_documentation_exists():
    """Тест, проверяющий, что документация создана"""
    
    # Проверяем, что документация существует
    with open('/workspace/MULTIAGENT_INSTRUCTIONS.md', 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Проверяем, что документация содержит ключевые разделы
    assert "Структурированный вывод" in content, "Документация должна содержать раздел о структурированном выводе"
    assert "отсутствующих данных" in content, "Документация должна содержать раздел об обработке отсутствующих данных"
    assert "..." in content, "Документация должна упоминать использование '...'"
    
    print("✓ Документация создана и содержит необходимую информацию")

if __name__ == "__main__":
    print("Запуск простых тестов структурированного вывода...")
    test_instructions_content()
    test_schema_exists()
    test_documentation_exists()
    print("\n✓ Все тесты пройдены успешно!")
    print("\nРезюме по изменениям:")
    print("- Инструкции генератора обновлены для использования '...' вместо генерации фиктивных данных")
    print("- Инструкции всех агентов обновлены для учета обработки отсутствующих данных")
    print("- Создана документация по работе мультиагентной системы")
    print("- Подтверждена корректность JSON-схем")